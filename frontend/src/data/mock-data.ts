type RecordSeed = Omit<SourceRecord, "evidence_spans"> & {
  spans: Array<{
    id: string;
    excerpt: string;
    field: string;
    status?: "extracted" | "review_required" | "quarantined";
    note?: string;
  }>;
};

function createRecord(seed: RecordSeed): SourceRecord {
  const { spans, ...record } = seed;
  return {
    ...record,
    evidence_spans: spans.map((span) => {
      const start = seed.text.indexOf(span.excerpt);
      return {
        span_id: span.id,
        record_id: seed.record_id,
        start: Math.max(0, start),
        end: Math.max(0, start) + span.excerpt.length,
        text: span.excerpt,
        field: span.field,
        extraction_status: span.status ?? "extracted",
        normalization_note: span.note,
      };
    }),
  };
}

